"""Show what the installer would change, change nothing. stdlib only.

Everything is built in a scratch directory: the theme, a grub.cfg generated by the system's own grub-mkconfig with our hooks added
(a copy of grub-mkconfig is pointed at a scratch sysconfdir, so /etc/grub.d and /etc/default/grub are only read), the annotation and
the scene baking. Then it prints a unified diff of grub.cfg and /etc/default/grub and the list of files the installer would write.
Needs root for grub-mkconfig (it probes the disks). Immutable systems: the static grub.cfg is edited on a copy.

usage: material-grub-dryrun --pkg DIR --res WxH [--immutable] [--set KEY=value]... [--installer DIR] [--keep]
"""

import difflib
import os
import re
import shutil
import subprocess
import sys
import tempfile
from pathlib import Path

HERE = Path(__file__).resolve().parent


def arg(name, default=None):
    return sys.argv[sys.argv.index(name) + 1] if name in sys.argv else default


def args(name):
    return [sys.argv[i + 1] for i, a in enumerate(sys.argv) if a == name and i + 1 < len(sys.argv)]


def apply_sets(text, sets):
    """The installer's rule for /etc/material-grub.conf: replace the sample (or existing) line, else append."""
    for kv in sets:
        k, _, v = kv.partition("=")
        if re.search(rf"^#?{re.escape(k)}=", text, re.M):
            text = re.sub(rf"^#?{re.escape(k)}=.*$", f"{k}={v}", text, flags=re.M)
        else:
            text += ("" if text.endswith("\n") or not text else "\n") + f"{k}={v}\n"
    return text


def set_gfxmode(text, res):
    if re.search(r"^GRUB_GFXMODE=", text, re.M):
        return re.sub(r"^GRUB_GFXMODE=.*$", f"GRUB_GFXMODE={res}", text, flags=re.M)
    return text + ("" if text.endswith("\n") else "\n") + f"GRUB_GFXMODE={res}\n"


def diff(old_path, old_text, new_text, new_label):
    d = list(
        difflib.unified_diff(
            old_text.splitlines(keepends=True),
            new_text.splitlines(keepends=True),
            fromfile=str(old_path),
            tofile=new_label,
        )
    )
    return d


def staged_files(installer_dir, pkg, res, immutable, sets, stage):
    """The files install/install.sh would write, found by letting it stage into a scratch DESTDIR (its --dest mode)."""
    cmd = ["sh", str(installer_dir / "install.sh"), "--dest", str(stage), "--no-run", "--pkg", str(pkg), "--res", res]
    if immutable:
        cmd.append("--immutable")
    for kv in sets:
        cmd += ["--set", kv]
    subprocess.run(cmd, check=True, capture_output=True, text=True)
    out = []
    for p in sorted(stage.rglob("*")):
        if p.is_file() or p.is_symlink():
            out.append("/" + str(p.relative_to(stage)))
    return out


def summarize(files):
    groups = {}
    for f in files:
        key = f
        if f.startswith("/usr/share/material-grub/") or f.startswith("/var/lib/material-grub/pkg/"):
            key = "/".join(f.split("/")[: 4 if f.startswith("/usr/") else 5]) + "/ (the theme package)"
        groups.setdefault(key, 0)
        groups[key] += 1
    return [f"{k}   [{n} files]" if n > 1 else k for k, n in groups.items()]


def mkconfig_copy(scratch, real_default_grub, hooks_dir):
    """A copy of grub-mkconfig that reads its configuration from scratch/etc instead of /etc."""
    mk = shutil.which("grub2-mkconfig") or shutil.which("grub-mkconfig")
    if not mk:
        sys.exit("dry run: grub-mkconfig not found")
    text = Path(mk).read_text()
    etc = scratch / "etc"
    new, n = re.subn(r"(?m)^sysconfdir=.*$", f'sysconfdir="{etc}"', text)
    if n == 0:
        sys.exit("dry run: cannot redirect this grub-mkconfig (no sysconfdir= line); use the real install instead")
    (scratch / "bin").mkdir()
    copy = scratch / "bin" / Path(mk).name  # same name as the real one: it shows in the generated header
    copy.write_text(new)
    copy.chmod(0o755)
    (etc / "default").mkdir(parents=True)
    (etc / "grub.d").mkdir()
    real_d = Path("/etc/grub.d")
    if real_d.is_dir():
        for f in sorted(real_d.iterdir()):
            (etc / "grub.d" / f.name).symlink_to(f.resolve())
    for name in ("05_material", "15_material_menu", "90_material_system"):  # ours replace any installed older copy
        target = etc / "grub.d" / name
        if target.exists() or target.is_symlink():
            target.unlink()
        shutil.copy(hooks_dir / name, target)
        target.chmod(0o755)
    extra = Path("/etc/default/grub.d")
    if extra.is_dir():
        (etc / "default/grub.d").symlink_to(extra)
    return copy, "--no-grubenv-update" in text


def main():
    pkg = Path(arg("--pkg"))
    res = arg("--res", "1920x1080")
    immutable = "--immutable" in sys.argv
    sets = args("--set")
    installer = Path(arg("--installer", str(HERE.parent)))
    scratch = Path(tempfile.mkdtemp(prefix="material-grub-dryrun."))
    try:
        return run(scratch, pkg, res, immutable, sets, installer)
    finally:
        if "--keep" in sys.argv:
            print(f"\nscratch directory kept: {scratch}")
        else:
            shutil.rmtree(scratch, ignore_errors=True)


def run(scratch, pkg, res, immutable, sets, installer):
    out = sys.stdout
    files = staged_files(installer, pkg, res, immutable, sets, scratch / "stage")
    cfg_real = next((Path(p) for p in ("/boot/grub2/grub.cfg", "/boot/grub/grub.cfg") if Path(p).exists()), None)
    print("DRY RUN: nothing below has been written to this system.\n", file=out)
    print("Files the installer would write:", file=out)
    for f in summarize(files):
        print(f"  {f}", file=out)
    extra = [
        "/var/backups/material-grub/ (copies of your GRUB files, first run only)",
        "/var/lib/material-grub/ (entry state for the scene renderer)",
    ]
    if immutable:
        extra.append(
            f"{cfg_real or '/boot/grub2/grub.cfg'} (edited in place; the original is kept in /var/backups/material-grub)"
        )
    else:
        extra += [
            "/etc/default/grub (GRUB_GFXMODE=" + res + ")",
            f"{cfg_real or '/boot/grub2/grub.cfg'} (regenerated)",
            f"{(cfg_real or Path('/boot/grub2/grub.cfg')).parent}/themes/material/ (the assembled theme)",
        ]
    for e in extra:
        print(f"  {e}", file=out)
    if os.geteuid() != 0:
        print(
            "\nNot running as root: the grub.cfg diff needs root (grub-mkconfig probes the disks). Run: sudo ./install.sh --dry-run",
            file=out,
        )
        return 1
    if cfg_real is None:
        print("\nNo grub.cfg found in /boot/grub2 or /boot/grub: nothing to compare against.", file=out)
        return 1
    gdir = cfg_real.parent

    conf_real = Path("/etc/material-grub.conf")
    conf_text = conf_real.read_text() if conf_real.exists() else (installer / "material-grub.conf").read_text()
    conf = scratch / "material-grub.conf"
    conf.write_text(apply_sets(conf_text, sets))
    env = dict(os.environ, MATERIAL_STATE_DIR=str(scratch / "state"), MATERIAL_CONF=str(conf), MG_FORCE="1")
    work = scratch / "grub"
    work.mkdir()
    post = [
        sys.executable,
        str(pkg / "bin/material-grub-postprocess"),
        "--pkg",
        str(pkg),
        "--cfg",
        str(work / "grub.cfg"),
        "--mirrors",
        str(scratch / "mirrors"),
    ]
    mbase = None

    if immutable:
        shutil.copy2(cfg_real.resolve(), work / "grub.cfg")
        mbase = ("/" + str(gdir.relative_to("/boot")) if os.path.ismount("/boot") else str(gdir)) + "/material"
        post += [
            "--immutable",
            "--res",
            res,
            "--timeout",
            "5",
            "--backup",
            str(scratch / "backup"),
            "--mirrorbase",
            mbase,
        ]
        old_default = new_default = None
    else:
        default_real = Path("/etc/default/grub")
        old_default = default_real.read_text() if default_real.exists() else ""
        new_default = set_gfxmode(old_default, res)
        mk, can_skip_env = mkconfig_copy(scratch, default_real, installer)
        (scratch / "etc/default/grub").write_text(new_default)
        env.update(MATERIAL_PKG=str(pkg), MATERIAL_GRUBDIR=str(gdir), MATERIAL_BUILD_DIR=str(work / "themes/material"))
        cmd = ["sh", str(mk)] + (["--no-grubenv-update"] if can_skip_env else []) + ["-o", str(work / "grub.cfg")]
        r = subprocess.run(cmd, capture_output=True, text=True, env=env)
        if r.returncode != 0 or not (work / "grub.cfg").exists():
            print("\ngrub-mkconfig failed in the scratch run:\n" + r.stderr[-1500:], file=out)
            return 1
        post += ["--theme", str(work / "themes/material")]

    r = subprocess.run(post, capture_output=True, text=True, env=env)
    if r.returncode != 0:
        print(
            "\nThe install would be ROLLED BACK by the safety net (the scratch run failed validation):\n" + r.stderr,
            file=out,
        )
        return 1

    new_cfg = (
        (work / "grub.cfg").read_text().replace(str(scratch / "etc"), "/etc")
    )  # the header names the scratch directory
    old_cfg = cfg_real.read_text()
    d = diff(cfg_real, old_cfg, new_cfg, "(after the install)")
    print(f"\n=== {cfg_real}: {len(d)} diff lines" + (" (identical)" if not d else ""), file=out)
    out.writelines(d if d else [])
    if new_default is not None:
        d2 = diff("/etc/default/grub", old_default, new_default, "(after the install)")
        print("\n=== /etc/default/grub: " + ("unchanged" if not d2 else f"{len(d2)} diff lines"), file=out)
        out.writelines(d2)
    print("\nNothing was changed. To install: sudo ./install.sh" + (f" --res {res}" if res else ""), file=out)
    return 0
