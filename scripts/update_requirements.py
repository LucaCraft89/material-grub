#!/usr/bin/env python3
"""Write requirements.txt (exact versions + sha256 of every release file) from requirements.in. stdlib only.

  update_requirements.py           rewrite requirements.txt from requirements.in (asks pypi.org for the hashes)
  update_requirements.py --check   fail if requirements.txt differs from what requirements.in produces, or a pin is not on PyPI

The hashes cover every wheel and the sdist of the pinned release, so the file works on every platform and Python in its markers.
Install with: pip install --require-hashes -r requirements.txt"""

import json
import re
import sys
import urllib.request
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
HEADER = """# Generated by scripts/update_requirements.py from requirements.in. Do not edit by hand.
# Install with: pip install --require-hashes -r requirements.txt
"""


def parse(text):
    pins = []
    for line in text.splitlines():
        line = line.split("#", 1)[0].strip()
        if not line:
            continue
        m = re.fullmatch(r"([A-Za-z0-9_.-]+)==([0-9][^\s;]*)\s*(?:;\s*(.+))?", line)
        if not m:
            sys.exit(f"requirements.in: cannot read {line!r} (expected name==version [; marker])")
        pins.append((m[1], m[2], (m[3] or "").strip()))
    return pins


def hashes(name, version):
    url = f"https://pypi.org/pypi/{name}/{version}/json"
    with urllib.request.urlopen(url, timeout=60) as r:
        files = json.load(r)["urls"]
    out = sorted({f["digests"]["sha256"] for f in files})
    if not out:
        sys.exit(f"{name}=={version}: no files on PyPI")
    return out


def render(pins):
    out = [HEADER]
    for name, version, marker in pins:
        req = f"{name}=={version}" + (f" ; {marker}" if marker else "")
        out.append(req + " \\\n" + " \\\n".join(f"    --hash=sha256:{h}" for h in hashes(name, version)) + "\n")
    return "\n".join(out)


def main():
    pins = parse((ROOT / "requirements.in").read_text())
    text = render(pins)
    target = ROOT / "requirements.txt"
    if "--check" in sys.argv:
        if not target.exists() or target.read_text() != text:
            sys.exit("requirements.txt is out of date: run `make update-requirements`")
        print(f"requirements.txt ok ({len(pins)} pins)")
        return
    target.write_text(text)
    print(f"wrote {target} ({len(pins)} pins)")


if __name__ == "__main__":
    main()
